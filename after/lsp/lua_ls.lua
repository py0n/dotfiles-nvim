-- after/lsp/lua_ls.lua
--
-- lua-language-server (lua_ls) の LSP 設定
--
-- 目的:
-- - Neovim 設定やプラグイン開発で Lua を書く際の体験を安定させる
-- - 「lua_ls がうるさい / 役に立たない」状態を避ける（診断・補完の最適化）
-- - Neovim 0.11+ の LSP 設計に合わせ、設定は after/lsp に集約する
--
-- 設計方針:
-- - ここでは「lua_ls 固有の settings」を定義する
-- - capabilities など共通項は lua/lsp.lua (vim.lsp.config('*', ...)) に寄せる
-- - 設定はできるだけ “Neovim の実態” に合わせる：
--   - ランタイムは LuaJIT
--   - vim グローバルを既知扱い
--   - runtime / plugin の Lua ファイルが参照できるようにする
--
-- 注意:
-- - workspace.library を無闇に広げると重くなるので、必要最小限にする
-- - 診断の抑制は「隠す」ではなく「ノイズを減らす」目的で行う

---@type vim.lsp.Config
return {
  ---------------------------------------------------------------------------
  -- settings
  --
  -- lua_ls が理解する設定の本体。
  -- https://luals.github.io/wiki/settings/ （参考）※URL はコメントなのでOK
  ---------------------------------------------------------------------------
  settings = {
    Lua = {
      -----------------------------------------------------------------------
      -- runtime
      --
      -- Neovim の Lua は基本的に LuaJIT 上で動くため明示する。
      -- これにより標準ライブラリ解釈や型推論が改善する。
      -----------------------------------------------------------------------
      runtime = {
        version = 'LuaJIT',
      },

      -----------------------------------------------------------------------
      -- diagnostics
      --
      -- Neovim の Lua では `vim` グローバルが前提になるため、
      -- “undefined global 'vim'” を出さないようにする。
      --
      -- NOTE:
      -- - globals を増やしすぎると本物の typo を見逃すので最小限にする
      -----------------------------------------------------------------------
      diagnostics = {
        globals = { 'vim' },
      },

      -----------------------------------------------------------------------
      -- workspace
      --
      -- library:
      -- - lua_ls が “参照して良い” ライブラリパスを指定する。
      -- - Neovim の runtime Lua を見せると `vim.*` 周辺の補完が強くなる。
      --
      -- checkThirdParty = false:
      -- - プロジェクト内の “3rd party” 推定（例: luv, OpenResty 等）を抑制。
      -- - 過剰な通知や意図しない推定を避ける目的。
      --
      -- NOTE:
      -- - library を巨大にすると解析コストが上がり、補完が重くなる。
      -- - 必要なら project-local で追加する（nvim-config-local 等と相性良い）
      -----------------------------------------------------------------------
      workspace = {
        library = {
          -- Neovim ランタイム（vim.* の補完に効く）
          vim.env.VIMRUNTIME,
        },
        checkThirdParty = false,
      },

      -----------------------------------------------------------------------
      -- telemetry
      --
      -- 解析統計の送信を無効化（好み + 予期しない通信を避ける）
      -----------------------------------------------------------------------
      telemetry = {
        enable = false,
      },

      -----------------------------------------------------------------------
      -- completion
      --
      -- callSnippet:
      -- - 補完のスニペット挙動。Editor の snippet 体系に合わせる。
      -- - "Replace" は補完確定時に引数スニペットを適切に挿入しやすい。
      -----------------------------------------------------------------------
      completion = {
        callSnippet = 'Replace',
      },
    },
  },

  ---------------------------------------------------------------------------
  -- (任意) on_new_config
  --
  -- 特殊な場合のみ使う。
  -- 例: プロジェクトごとに workspace.library を追加したい等。
  --
  -- 基本は「重くなる」ので、必要が出てから導入が安全。
  ---------------------------------------------------------------------------
  -- on_new_config = function(new_config, root_dir)
  --   -- project root に応じて設定をいじる例（必要になったら）
  -- end,
}
